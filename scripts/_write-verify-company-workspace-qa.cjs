const fs = require("fs");
const path = require("path");
const target = path.join(__dirname, "verify-company-workspace-qa.mjs");
const lines = [];
function L(s) { lines.push(s); }
L("/**");
L(" * Company Workspace stabilization QA (Sprint 11)");
L(" * Run: node scripts/verify-company-workspace-qa.mjs");
L(" */");
L('import { readFileSync } from "node:fs";');
L('import { dirname, join } from "node:path";');
L('import { fileURLToPath } from "node:url";');
L('import { chromium } from "playwright";');
L("");
L('const root = join(dirname(fileURLToPath(import.meta.url)), "..");');
L('const BASE = process.env.QA_BASE_URL || "http://localhost:4173";');
L("");
L("const COMPANY_ROUTES = [");
L('  "/company/dashboard",');
L('  "/company/information",');
L('  "/company/sites",');
L('  "/company/organization",');
L('  "/company/departments",');
L('  "/company/employees",');
L('  "/company/positions",');
L('  "/company/branding",');
L('  "/company/document-footer",');
L("];");
L("");
L("const QUICK_LINKS = [");
L('  { label: "QR Engine", path: "/qr/dashboard" },');
L('  { label: "\\uC124\\uBE44 \\uD604\\uD669", path: "/equipment-status" },');
L('  { label: "\\uC81C\\uD488 \\uD604\\uD669", path: "/equipment-status", query: "view=product" },');
L('  { label: "\\uBB38\\uC11C\\uAD00\\uB9AC", path: "/documents" },');
L("];");
L("");
L('const ERROR_BOUNDARY_SNIPPET = "\\uC77C\\uC2DC\\uC801\\uC778 \\uC624\\uB958";');
L("");
L("function loadAdminCredentials() {");
L('  const source = readFileSync(join(root, "src/config/titanLoginSystem.js"), "utf8");');
L('  const loginId = source.match(/loginId:\\s*"([^"]+)"/)?.[1] ?? "admin";');
L('  const password = source.match(/defaultPassword:\\s*"([^"]+)"/)?.[1] ?? "1234";');
L("  return { loginId, password };");
L("}");
L("");
L("function assert(condition, message) {");
L("  if (!condition) throw new Error(message);");
L("}");
L("");
L("async function login(page, { loginId, password }) {");
L('  await page.goto(BASE + "/login", { waitUntil: "networkidle" });');
L('  await page.fill(\'input[name="loginId"]\', loginId);');
L('  await page.fill(\'input[name="password"]\', password);');
L('  await page.click(\'button[type="submit"]\');');
L('  const firstLoginModal = page.locator(".titan-login-modal");');
L('  if (await firstLoginModal.isVisible().catch(() => false)) {');
L('    await page.getByRole("button", { name: "\\uB098\\uC911\\uC5D0" }).click();');
L('  }');
L('  await page.waitForURL((url) => !url.pathname.includes("/login"), { timeout: 20000 });');
L("}");
L("");
L("async function expectHealthyPage(page, label) {");
L('  const bodyText = await page.locator("body").innerText();');
L('  assert(bodyText.length > 200, label + ": page body too short (possible white screen)");');
L('  assert(!bodyText.includes(ERROR_BOUNDARY_SNIPPET), label + ": error boundary visible");');
L('  const rootEl = page.locator("#root");');
L('  await rootEl.waitFor({ state: "attached" });');
L("  const rootText = (await rootEl.innerText()).trim();");
L('  assert(rootText.length > 50, label + ": #root empty or too short");');
L("}");
L("");
L("function urlMatchesQuickLink(pageUrl, link) {");
L("  const u = new URL(pageUrl);");
L("  if (!u.pathname.includes(link.path)) return false;");
L("  if (link.query) return u.search.includes(link.query);");
L("  return true;");
L("}");
L("");
L("async function main() {");
L("  const errors = [];");
L("  const consoleErrors = [];");
L("  const results = [];");
L("");
L("  const browser = await chromium.launch({ headless: true });");
L("  const page = await browser.newPage();");
L("");
L('  page.on("pageerror", (err) => errors.push("pageerror: " + err.message));');
L('  page.on("console", (msg) => {');
L('    if (msg.type() === "error") consoleErrors.push(msg.text());');
L("  });");
L("");
L("  const creds = loadAdminCredentials();");
L("  await login(page, creds);");
L("");
L('  await page.goto(BASE + "/company/dashboard", { waitUntil: "networkidle" });');
L('  await expectHealthyPage(page, "direct /company/dashboard");');
L('  results.push({ check: "direct /company/dashboard", ok: true });');
L("");
L('  await page.reload({ waitUntil: "networkidle" });');
L('  await expectHealthyPage(page, "F5 /company/dashboard");');
L('  results.push({ check: "F5 /company/dashboard", ok: true });');
L("");
L("  for (const route of COMPANY_ROUTES) {");
L('    await page.goto(BASE + route, { waitUntil: "networkidle" });');
L('    await expectHealthyPage(page, "direct " + route);');
L('    results.push({ check: "direct " + route, ok: true });');
L("");
L('    await page.reload({ waitUntil: "networkidle" });');
L('    await expectHealthyPage(page, "F5 " + route);');
L('    results.push({ check: "F5 " + route, ok: true });');
L("  }");
L("");
L('  await page.goto(BASE + "/company/dashboard", { waitUntil: "networkidle" });');
L('  const tabs = page.locator("nav.company-workspace-nav a");');
L("  const tabCount = await tabs.count();");
L('  assert(tabCount === 9, "expected 9 top tabs, got " + tabCount);');
L("  for (let i = 0; i < tabCount; i += 1) {");
L("    const tab = tabs.nth(i);");
L('    const label = ((await tab.innerText()) || "").trim();');
L("    await tab.click();");
L('    await page.waitForLoadState("networkidle");');
L('    await expectHealthyPage(page, "tab click " + (i + 1) + " " + label);');
L('    results.push({ check: "tab click " + label, ok: true, url: page.url() });');
L("  }");
L("");
L('  await page.goto(BASE + "/company/information", { waitUntil: "networkidle" });');
L('  await page.locator("a.company-workspace-rail__home").click();');
L("  await page.waitForURL(/\\/company\\/dashboard$/, { timeout: 10000 });");
L('  await expectHealthyPage(page, "sidebar home link");');
L('  results.push({ check: "sidebar home link", ok: true });');
L("");
L("  for (const link of QUICK_LINKS) {");
L('    await page.goto(BASE + "/company/dashboard", { waitUntil: "networkidle" });');
L("    await page");
L('      .locator("aside.company-workspace-rail a.company-workspace-rail__link--quick", { hasText: link.label })');
L("      .click();");
L('    await page.waitForLoadState("networkidle");');
L('    assert(urlMatchesQuickLink(page.url(), link), "Quick link " + link.label + " -> " + page.url());');
L('    await expectHealthyPage(page, "quick link " + link.label);');
L('    results.push({ check: "quick link " + link.label, ok: true, url: page.url() });');
L("  }");
L("");
L("  await browser.close();");
L("");
L("  const uniqueConsole = [...new Set(consoleErrors)].filter(");
L('    (line) => !line.includes("favicon") && !line.includes("DevTools")');
L("  );");
L("  const uniquePageErrors = [...new Set(errors)];");
L("");
L("  if (uniquePageErrors.length) {");
L('    console.error("Page errors:");');
L('    uniquePageErrors.forEach((line) => console.error("  - " + line));');
L("    process.exit(1);");
L("  }");
L("");
L("  if (uniqueConsole.length) {");
L('    console.error("Console errors:");');
L('    uniqueConsole.forEach((line) => console.error("  - " + line));');
L("    process.exit(1);");
L("  }");
L("");
L('  console.log("Company Workspace QA passed");');
L('  console.log("   base=" + BASE + " | checks=" + results.length);');
L("  for (const row of results) {");
L('    console.log("   - " + row.check + (row.url ? " -> " + row.url : ""));');
L("  }");
L("}");
L("");
L("main().catch((err) => {");
L('  console.error("Company Workspace QA failed:", err.message);');
L("  process.exit(1);");
L("});");
fs.writeFileSync(target, lines.join("\n") + "\n", { encoding: "utf8" });
const b = fs.readFileSync(target);
console.log("Wrote", target, "len", b.length, "isUtf16", b[1] === 0);