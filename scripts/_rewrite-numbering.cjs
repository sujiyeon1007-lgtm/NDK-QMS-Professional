const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "src");

const configLines = [
'/**',
' * Project TITAN - document numbering config',
' * Pattern: {companyAbbr}-{prefix}-{seq4}',
' */',
'export const TITAN_NUMBERING_STORAGE_KEY = "project-titan-document-numbering-v1";',
'',
'export const TITAN_DOCUMENT_NUMBER_TYPES = {',
'  customer: { id: "customer", label: "\uac70\ub798\ucc98", prefix: "C", example: "DS-C-0001", description: "\uac70\ub798\ucc98 Master" },',
'  product: { id: "product", label: "\uc81c\ud488", prefix: "P", example: "DS-P-0001", description: "\uc81c\ud488 Master" },',
'  inbound: { id: "inbound", label: "\uc785\uace0", prefix: "I", example: "DS-I-0001", description: "\uc785\uace0" },',
'  lot: { id: "lot", label: "LOT", prefix: "L", example: "DS-L-0001", description: "LOT" },',
'  production: { id: "production", label: "\uc0dd\uc0b0", prefix: "W", example: "DS-W-0001", description: "\uc0dd\uc0b0" },',
'  inspection: { id: "inspection", label: "\uac80\uc0ac", prefix: "Q", example: "DS-Q-0001", description: "\uac80\uc0ac" },',
'  certificate: { id: "certificate", label: "\uc131\uc801\uc11c", prefix: "CT", example: "DS-CT-0001", description: "\uc131\uc801\uc11c" },',
'  shipment: { id: "shipment", label: "\ucd9c\uace0", prefix: "S", example: "DS-S-0001", description: "\ucd9c\uace0" },',
'  document: { id: "document", label: "\ubb38\uc11c", prefix: "D", example: "DS-D-0001", description: "\ubb38\uc11c" },',
'};',
'',
'export const TITAN_NUMBERING_PATTERN = "{companyAbbr}-{prefix}-{seq4}";',
'export const TITAN_NUMBERING_SEQ_PAD = 4;',
'',
'export function getDefaultNumberingPrefixes() {',
'  return Object.fromEntries(Object.values(TITAN_DOCUMENT_NUMBER_TYPES).map((item) => [item.id, item.prefix]));',
'}',
'',
'export function buildNumberingPreview(companyAbbr, prefix, seq = 1) {',
'  const abbr = String(companyAbbr ?? "XX").trim().toUpperCase() || "XX";',
'  const safePrefix = String(prefix ?? "X").trim().toUpperCase() || "X";',
'  return `${abbr}-${safePrefix}-${String(seq).padStart(TITAN_NUMBERING_SEQ_PAD, "0")}`;',
'}',
'',
];
fs.writeFileSync(path.join(root, "config", "titanDocumentNumbering.js"), configLines.join("\n"), "utf8");

const utilLines = [
'import {',
'  TITAN_DOCUMENT_NUMBER_TYPES,',
'  TITAN_NUMBERING_STORAGE_KEY,',
'  buildNumberingPreview,',
'  getDefaultNumberingPrefixes,',
'} from "../config/titanDocumentNumbering";',
'import { getCompanyAbbreviation } from "./companyAbbreviation";',
'import { getMasterDataByCategory } from "./masterData";',
'',
'function safeReadSettings() {',
'  try {',
'    const raw = globalThis.sessionStorage?.getItem(TITAN_NUMBERING_STORAGE_KEY);',
'    if (!raw) return { prefixes: getDefaultNumberingPrefixes() };',
'    const parsed = JSON.parse(raw);',
'    return { prefixes: { ...getDefaultNumberingPrefixes(), ...(parsed?.prefixes ?? {}) } };',
'  } catch {',
'    return { prefixes: getDefaultNumberingPrefixes() };',
'  }',
'}',
'',
'function safeWriteSettings(settings) {',
'  try {',
'    globalThis.sessionStorage?.setItem(TITAN_NUMBERING_STORAGE_KEY, JSON.stringify(settings));',
'    return true;',
'  } catch {',
'    return false;',
'  }',
'}',
'',
'export function getNumberingSettings() { return safeReadSettings(); }',
'export function getNumberingPrefixes() { return safeReadSettings().prefixes; }',
'',
'export function saveNumberingPrefixes(prefixes) {',
'  const current = safeReadSettings();',
'  const next = {',
'    ...current,',
'    prefixes: {',
'      ...current.prefixes,',
'      ...Object.fromEntries(Object.entries(prefixes ?? {}).map(([key, value]) => [key, String(value ?? "").trim().toUpperCase()])),',
'    },',
'  };',
'  safeWriteSettings(next);',
'  return next;',
'}',
'',
'export function resetNumberingPrefixes() {',
'  const next = { prefixes: getDefaultNumberingPrefixes() };',
'  safeWriteSettings(next);',
'  return next;',
'}',
'',
'export function getNumberingPrefix(type) {',
'  const meta = TITAN_DOCUMENT_NUMBER_TYPES[type];',
'  if (!meta) return "X";',
'  const prefixes = getNumberingPrefixes();',
'  return String(prefixes[type] ?? meta.prefix).trim().toUpperCase() || meta.prefix;',
'}',
'',
'export function resolveCompanyAbbreviation(companyNameOrRow) {',
'  if (companyNameOrRow && typeof companyNameOrRow === "object") return getCompanyAbbreviation(companyNameOrRow);',
'  const name = String(companyNameOrRow ?? "").trim();',
'  if (!name) return "XX";',
'  const company = getMasterDataByCategory("companies").find((row) => row.name === name);',
'  if (company) return getCompanyAbbreviation(company);',
'  return name.slice(0, 2).toUpperCase() || "XX";',
'}',
'',
'function buildNumberPattern(companyAbbr, prefix) {',
'  const abbr = String(companyAbbr ?? "XX").trim().toUpperCase() || "XX";',
'  const safePrefix = String(prefix ?? "X").trim().toUpperCase() || "X";',
'  return `${abbr}-${safePrefix}-`;',
'}',
'',
'function extractMaxSequence(existingValues, pattern) {',
'  const escaped = pattern.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&");',
'  const regex = new RegExp(`^${escaped}(\\\\d+)$`);',
'  return existingValues.reduce((max, value) => {',
'    const match = String(value ?? "").trim().match(regex);',
'    if (!match) return max;',
'    const seq = Number(match[1]);',
'    return Number.isFinite(seq) ? Math.max(max, seq) : max;',
'  }, 0);',
'}',
'',
'export function generateTitanDocumentNumber(type, companyAbbrOrName, existingValues = null) {',
'  const companyAbbr = resolveCompanyAbbreviation(companyAbbrOrName);',
'  const prefix = getNumberingPrefix(type);',
'  const pattern = buildNumberPattern(companyAbbr, prefix);',
'  let values = existingValues;',
'  if (!values) {',
'    if (type === "product") {',
'      const companyName =',
'        typeof companyAbbrOrName === "object"',
'          ? companyAbbrOrName?.name',
'          : getMasterDataByCategory("companies").find((row) => getCompanyAbbreviation(row) === companyAbbr)?.name ?? companyAbbrOrName;',
'      values = getMasterDataByCategory("products").filter((row) => !companyName || row.company === companyName).map((row) => row.code);',
'    } else if (type === "customer") {',
'      values = getMasterDataByCategory("companies").map((row) => row.code);',
'    } else {',
'      values = [];',
'    }',
'  }',
'  return buildNumberingPreview(companyAbbr, prefix, extractMaxSequence(values, pattern) + 1);',
'}',
'',
'export function getNumberingRuleRows(companyAbbr = "DS") {',
'  return Object.values(TITAN_DOCUMENT_NUMBER_TYPES).map((item) => ({',
'    id: item.id,',
'    category: item.label,',
'    prefix: getNumberingPrefix(item.id),',
'    format: "{companyAbbr}-" + getNumberingPrefix(item.id) + "-{seq4}",',
'    example: buildNumberingPreview(companyAbbr, getNumberingPrefix(item.id), 1),',
'    source: item.description,',
'    status: "\uc6b4\uc601",',
'  }));',
'}',
'',
];
fs.writeFileSync(path.join(root, "utils", "titanDocumentNumbering.js"), utilLines.join("\n"), "utf8");
console.log('rewrote numbering files utf8');
